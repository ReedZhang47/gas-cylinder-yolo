r"""Print the phase-7 result tables straight from the summary JSONs.

Usage:
  & D:\yolo\.venv\Scripts\python.exe D:\yolo\scripts\show_results.py

Sources (authoritative numbers, regenerated by the eval scripts):
  phase7_realv2_summary.json   <- eval_realv2.py       (v2 main results)
  phase7_300ep_check.json      <- eval_real60_300ep.py (training-budget check)
"""
import json
from pathlib import Path

ROOT = Path(r"D:\yolo")
V2 = ROOT / "phase7_realv2_summary.json"
BUDGET = ROOT / "phase7_300ep_check.json"
WEIGHTS = ["yolov8s", "yolov8m", "yolo11s", "yolo11m", "yolo26s", "yolo26m"]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def get(rows, tag):
    for r in rows or []:
        if r["tag"] == tag:
            return r
    return {}


def fmt(r):
    return f"{r['mAP50']:.3f} / {r['mAP50-95']:.3f}" if "mAP50" in r else "     -      "


def main():
    d = load(V2)
    if d:
        print(f"=== v2 main results ({d['meta']['date']}) — mAP50 / mAP50-95 ===")
        print(f"{'weight':9s} {'gen t93':13s} {'gen t33':13s} {'real60 t33':13s} "
              f"{'real60 t93(leak)':17s} {'gen-real':9s}")
        for w in WEIGHTS:
            g93 = fmt(get(d.get("gen_last_test93"), w))
            g33 = fmt(get(d.get("gen_last_test33"), w))
            r33 = fmt(get(d.get("real60_last_test33"), w))
            r93 = fmt(get(d.get("real60_last_test93"), w))
            a, b = get(d.get("gen_last_test33"), w), get(d.get("real60_last_test33"), w)
            delta = f"{a['mAP50-95'] - b['mAP50-95']:+.3f}" if a and b else "-"
            print(f"{w:9s} {g93:13s} {g33:13s} {r33:13s} {r93:17s} {delta:9s}")
    else:
        print(f"(missing {V2})")

    b = load(BUDGET)
    if b:
        print(f"\n=== training-budget check ({b['meta']['date']}): real arm 100ep -> 300ep, mAP50-95 ===")
        for w in WEIGHTS:
            a33, c33 = get(b.get("ref_100ep_test33"), w), get(b.get("real300_test33"), w)
            a93, c93 = get(b.get("ref_100ep_test93"), w), get(b.get("real300_test93"), w)
            g33 = get(b.get("ref_gen_last_test33"), w)
            p = lambda r: f"{r['mAP50-95']:.3f}" if "mAP50-95" in r else "  -  "
            print(f"{w:9s} test33 {p(a33)} -> {p(c33)} (gen {p(g33)})    "
                  f"test93 {p(a93)} -> {p(c93)}")
    else:
        print(f"\n(missing {BUDGET})")


if __name__ == "__main__":
    main()
